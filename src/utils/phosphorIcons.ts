/**
 * Retourne la classe CSS Phosphor complète pour un nom d'icône.
 * Accepte : nom nu (`id-card`), classe FA (`fa-solid fa-id-card`),
 * classe Phosphor déjà convertie (`ph ph-car`).
 */
export function phClass(name?: string | null, fallback = "file-text"): string {
  const raw = (name || "").trim();
  if (!raw) return `ph ph-${fallback}`;
  if (raw.startsWith("ph ")) return raw;

  const cleaned = raw
    .replace(/\bfa-(solid|regular|brands)\b/g, "")
    .replace(/^fa-/, "")
    .trim()
    .split(/\s+/)[0]
    .replace(/^fa-/, "");

  const mapped = LEGACY_TO_PHOSPHOR[cleaned];
  if (mapped) return `ph ph-${mapped}`;
  if (cleaned) return `ph ph-${cleaned}`;
  return `ph ph-${fallback}`;
}
